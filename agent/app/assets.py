import asyncio
import io
import warnings
from pathlib import Path
from uuid import uuid4

from PIL import Image

from app.config import Settings
from app.errors import AgentError
from app.schemas import Asset
from app.storage import Store

FORMATS = {"JPEG": "image/jpeg", "PNG": "image/png", "WEBP": "image/webp"}


def inspect_image(data: bytes, settings: Settings) -> str:
    if not data or len(data) > settings.max_image_bytes:
        raise AgentError("图片为空或超过单张上传大小限制。", status=413)
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(data)) as image:
                mime = FORMATS.get(image.format)
                if not mime or image.width * image.height > settings.max_image_pixels:
                    raise AgentError("仅支持大小合规的 JPEG、PNG、WebP 图片。")
                image.verify()
                return mime
    except AgentError:
        raise
    except Exception as exc:
        raise AgentError("图片损坏或格式不受支持。") from exc


class Assets:
    def __init__(self, store: Store, settings: Settings):
        self.store, self.settings = store, settings
        self.directory = settings.data_dir / "assets"
        self.directory.mkdir(parents=True, exist_ok=True)

    def path(self, asset: Asset) -> Path:
        # IDs are generated by this service, not derived from an uploaded filename.
        return self.directory / asset.id

    async def save(
        self,
        conversation_id: str,
        batch_id: str,
        data: bytes,
        filename: str,
        *,
        source_tool="upload",
        parent_id=None,
        role="original",
    ) -> Asset:
        mime = await asyncio.to_thread(inspect_image, data, self.settings)
        asset = Asset(
            id=uuid4().hex,
            conversation_id=conversation_id,
            batch_id=batch_id,
            filename=Path(filename.replace("\\", "/")).name,
            mime_type=mime,
            source_tool=source_tool,
            parent_id=parent_id,
            role=role,
        )
        path = self.path(asset)
        await asyncio.to_thread(path.write_bytes, data)
        try:
            await self.store.add_asset(asset)
        except BaseException:
            path.unlink(missing_ok=True)
            raise
        return asset

    async def read(self, asset: Asset) -> bytes:
        try:
            return await asyncio.to_thread(self.path(asset).read_bytes)
        except FileNotFoundError as exc:
            raise AgentError("图片文件已不存在，请重新上传。") from exc

    async def delete_files(self, ids: list[str]):
        for asset_id in ids:
            (self.directory / asset_id).unlink(missing_ok=True)
